"""Tests for PM-facing report generation."""

from __future__ import annotations

from datetime import UTC, datetime
from unittest.mock import AsyncMock, patch

import pytest

from shoal.core.journal import append_entry
from shoal.core.state import create_session, update_session
from shoal.models.config.workspace import TeamReportTargetConfig
from shoal.models.state import SessionStatus
from shoal.services.report import (
    generate_session_report,
    generate_sprint_report,
    generate_team_report,
    post_sprint_report,
)


@pytest.mark.asyncio
async def test_generate_session_report_returns_llm_report(mock_dirs) -> None:
    """Session report uses session state, journal data, and LLM output."""
    session = await create_session("alpha", "claude", "/tmp/repo")
    append_entry(session.id, "Implemented the report feature.", source="agent")

    with (
        patch(
            "shoal.services.report._latest_dreamer_summary",
            new=AsyncMock(return_value="Dreamer saw steady progress."),
        ),
        patch(
            "shoal.services.ai_client.call_llm",
            new=AsyncMock(return_value="## Current work\nThe agent is closing out the feature."),
        ),
    ):
        report = await generate_session_report("alpha", model="test-model")

    assert "# Session Report: alpha" in report
    assert "The agent is closing out the feature." in report
    assert "Generated by shoal report" in report


